#!/usr/bin/env python3
"""Writes traces/specs.tsv: every trace the study uses (name, group, tracegen arguments).

The groups map to docs/PREREGISTRATION.md. Confirmatory scenarios use trace seeds 1-12 (§2.1),
and the pilot uses the disjoint seeds 9001-9003 (§2.5). Regenerate this file with
    python3 scripts/trace_specs.py
and build the traces with scripts/build_traces.py.
"""
from pathlib import Path

CONFIRMATORY_SEEDS = range(1, 13)
PILOT_SEEDS = (9001, 9002, 9003)
OPS = 1_000_000
MIX = {"read": "0.80,0.10,0.10", "bal": "0.34,0.33,0.33", "churn": "0.10,0.45,0.45"}
SNAP = {  # file in data/snap/ -> windows in seconds (1 day, 1 week, 30 days)
    "CollegeMsg.txt": (86400, 604800, 2592000),
    "email-Eu-core-temporal.txt": (86400, 604800, 2592000),
    "sx-mathoverflow.txt": (86400, 604800, 2592000),
}

rows = []


def add(name, group, args):
    rows.append((name, group, args))


def churn(prefix, group, graph, n, deg, mix, query, seeds, ops=OPS):
    for s in seeds:
        add(f"{prefix}_s{s:02d}", group,
            f"churn --graph {graph} --n {n} --deg {deg} --mix {MIX[mix]} --ops {ops} --query {query} --seed {s}")


# RQ1, RQ2 and RQ3c cells: ER, average degree 4, balanced, uniform queries (T1-T11, T16).
for v in (1_000, 100_000, 1_000_000):
    churn(f"rq1_er_d4_bal_uni_v{v}", "rq1_rq2_rq3c", "er", v, 4, "bal", "uniform", CONFIRMATORY_SEEDS)

# RQ3 P1 (T12): read-heavy vs churn-heavy at V = 1e5.
churn("rq3_c1_er_d4_read_uni_v100000", "rq3_p1", "er", 100_000, 4, "read", "uniform", CONFIRMATORY_SEEDS)
churn("rq3_c2_er_d4_churn_uni_v100000", "rq3_p1", "er", 100_000, 4, "churn", "uniform", CONFIRMATORY_SEEDS)

# RQ3 P3 (T13): balanced at V = 1e4, uniform vs local; same seeds, so shared update streams.
churn("rq3_c3_er_d4_bal_uni_v10000", "rq3_p3", "er", 10_000, 4, "bal", "uniform", CONFIRMATORY_SEEDS)
churn("rq3_c4_er_d4_bal_loc_v10000", "rq3_p3", "er", 10_000, 4, "bal", "local", CONFIRMATORY_SEEDS)

# RQ3 exploratory cells named in the pre-registration.
churn("rq3x_er_d4_bal_uni_v100000", "rq3_exploratory", "er", 100_000, 4, "bal", "uniform", CONFIRMATORY_SEEDS)
churn("rq3x_er_d4_bal_loc_v100000", "rq3_exploratory", "er", 100_000, 4, "bal", "local", CONFIRMATORY_SEEDS)
churn("rq3x_er_d4_bal_cross_v100000", "rq3_exploratory", "er", 100_000, 4, "bal", "cross", CONFIRMATORY_SEEDS)
churn("rq3x_er_d4_bal_cross_v10000", "rq3_exploratory", "er", 10_000, 4, "bal", "cross", CONFIRMATORY_SEEDS)

# RQ3b (T14 B1, T15 B2): SIGMOD 2025 u_r workloads at V = 1e5, u_r = 1000 (amendment A2).
for s in CONFIRMATORY_SEEDS:
    add(f"rq3b_b1_path_ur1000_v100000_s{s:02d}", "rq3b",
        f"ur --graph path --n 100000 --ur 1000 --checkpoints 100 --qpc 10000 --seed {s}")
    add(f"rq3b_b2_er_m10n_ur1000_v100000_s{s:02d}", "rq3b",
        f"ur --graph er --n 100000 --m 1000000 --ur 1000 --checkpoints 100 --qpc 10000 --seed {s}")

# RQ5 (T17, T18): V = 1e4, average degree 8, balanced, uniform; RGG vs ER.
churn("rq5_rgg_d8_bal_uni_v10000", "rq5", "rgg", 10_000, 8, "bal", "uniform", CONFIRMATORY_SEEDS)
churn("rq5_er_d8_bal_uni_v10000", "rq5", "er", 10_000, 8, "bal", "uniform", CONFIRMATORY_SEEDS)

# Pilot (§2.5): disjoint seeds, balanced, V in {1e4, 1e5}. Only run-to-run variance is analyzed.
for v in (10_000, 100_000):
    churn(f"pilot_er_d4_bal_uni_v{v}", "pilot", "er", v, 4, "bal", "uniform", PILOT_SEEDS)

# Exploratory and RQ4 training/held-out families (3 seeds each).
EXP = range(1, 4)
churn("x_ba_d4_bal_uni_v100000", "exploratory", "ba", 100_000, 4, "bal", "uniform", EXP)
churn("x_rgg_d4_bal_uni_v100000", "exploratory", "rgg", 100_000, 4, "bal", "uniform", EXP)
for s in EXP:
    add(f"x_adversarial_v100000_k300_s{s:02d}", "exploratory",
        f"adversarial --n 100000 --clique 300 --ops 200000 --q 0.34 --seed {s}")
    add(f"x_leo_72x22_s{s:02d}", "held_out_leo", f"leo --planes 72 --sats 22 --steps 2000 --q 0.34 --seed {s}")
for fname, windows in SNAP.items():
    stem = Path(fname).stem.replace("-", "_").lower()
    for w in windows:
        for s in EXP:
            add(f"x_snap_{stem}_w{w}_s{s:02d}", "held_out_snap",
                f"window --input data/snap/{fname} --window {w} --q 0.34 --seed {s}")
for s in EXP:
    add(f"x_youtube_ur1000_s{s:02d}", "rq3b_exploratory",
        f"ur --graph edgelist --input data/snap/com-youtube.ungraph.txt --ur 1000 --checkpoints 100 --qpc 10000 --seed {s}")
    add(f"x_road_ny_ur1000_s{s:02d}", "exploratory",
        f"ur --graph dimacs --input data/dimacs/USA-road-d.NY.gr --ur 1000 --checkpoints 100 --qpc 10000 --seed {s}")

out = Path(__file__).resolve().parent.parent / "traces" / "specs.tsv"
out.parent.mkdir(exist_ok=True)
with out.open("w") as f:
    f.write("# name\tgroup\ttracegen arguments (generated by scripts/trace_specs.py; do not edit)\n")
    for name, group, args in rows:
        f.write(f"{name}\t{group}\t{args}\n")
print(f"wrote {len(rows)} specs to {out}")
